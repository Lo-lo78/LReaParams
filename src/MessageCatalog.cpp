void setSpeechMessageOverrides(const std::vector<SpeechMessageOverride>& values) {
    std::unordered_map<std::string, SpeechMessageOverride> next;
    for (const auto& value : values) {
        if (!value.id.empty() && (!value.enabled || !value.custom.empty()))
            next[value.id] = value;
    }
    overrides.swap(next);
}
void emitConfigurableSpeech(SpeechScope scope, const char* file, const char* expression,
    const std::function<void(const std::string&)>& output, const std::string& message) {
    // Zero overhead beyond the original callback when no messages are customized.
    if (overrides.empty()) { output(message); return; }
    const auto it = overrides.find(speechMessageId(scope, file, expression));
    if (it == overrides.end()) { output(message); return; }
    if (!it->second.enabled) return;
    if (it->second.custom.empty()) { output(message); return; }
    std::string replacement = utf8(it->second.custom);
    // {original} can preserve dynamic values such as the selected parameter,
    // track, numeric value or MIDI channel in a customized message.
    const std::string token = "{original}";
    std::size_t index = 0;
    while ((index = replacement.find(token, index)) != std::string::npos) {
        replacement.replace(index, token.size(), message);
        index += message.size();
    }
    if (!replacement.empty()) output(replacement);
}
